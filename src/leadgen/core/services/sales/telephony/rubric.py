"""Строгая шкала оценки холодного B2B-звонка.

Принципы (как в скоркартах отделов продаж): оцениваются наблюдаемые
действия, а не «старание»; у каждого критерия три уровня с явными
признаками; на каждый уровень — цитата-доказательство из разговора.
Итоговый балл считает код по уровням, а не модель «на глаз» — так
оценки сопоставимы между звонками и людьми.

Строгость: похвала только за действие, выполненное грамотно и с
результатом. Неумелая или невнятная попытка — не больше «частично»;
попытка, которая не дала ответа клиента по существу, — «не выполнено».
"""

from __future__ import annotations

from typing import Any

#: key, вес, что значит «выполнено», «частично», «не выполнено».
CRITERIA: tuple[tuple[str, int, str, str, str], ...] = (
    (
        "opening",
        1,
        "за 15–20 секунд назвал себя, компанию и понятную клиенту причину звонка; получил разрешение продолжить или зацепил интерес",
        "представился, но причина звонка размыта или вступление затянуто",
        "нет внятного представления и причины звонка, сразу продажа или сумбур",
    ),
    (
        "relevance",
        1,
        "повод привязан к бизнесу именно этого клиента (его сайт, отзывы, ниша, город)",
        "общий повод для ниши без конкретики о клиенте",
        "шаблон, подходящий любому, или повода нет",
    ),
    (
        "discovery",
        3,
        "задал 2+ открытых конкретных вопроса о ситуации и задачах клиента, клиент ответил по существу, менеджер уточнил ответ",
        "1 уместный вопрос с ответом клиента, либо вопросы есть, но поверхностные/закрытые",
        "вопросов нет, или вопросы невнятные/наводящие/риторические, или клиент по существу так и не ответил — квалификации нет",
    ),
    (
        "listening",
        1,
        "клиент говорит не меньше трети времени, менеджер не перебивает и опирается на сказанное клиентом",
        "монологи менеджера, но реплики клиента учитываются",
        "менеджер говорит почти всё время, перебивает или игнорирует сказанное",
    ),
    (
        "value",
        2,
        "предложение связано с тем, что сказал клиент, с конкретным результатом для его бизнеса",
        "выгода названа, но общая, без связи с ответами клиента",
        "перечисление услуг или «мы делаем всё» без выгоды для клиента",
    ),
    (
        "objections",
        2,
        "принял возражение, уточнил, что за ним стоит, ответил по сути и проверил, снято ли оно",
        "ответил на возражение, но шаблонно или не проверил реакцию",
        "сдался, спорил, проигнорировал или ответил не по сути",
    ),
    (
        "next_step",
        3,
        "конкретная договорённость: встреча/звонок с датой и временем, контакт ЛПР, согласованное действие с сроком",
        "размытый шаг без даты («пришлите информацию», «перезвоните как-нибудь»)",
        "разговор закончился без следующего шага",
    ),
    (
        "clarity",
        1,
        "говорит уверенно, понятно, без лишних слов-паразитов, вежливо",
        "местами сбивчиво или неуверенно",
        "невнятно, много пауз и паразитов, неуверенность мешает разговору",
    ),
)

LEVEL_POINTS = {"met": 2, "partial": 1, "not_met": 0}
#: Разговор короче — оценивать нечего (недозвон, сброс, автоответчик).
MIN_TALK_SEC = 30


def rubric_prompt() -> str:
    lines = [
        "ШКАЛА ОЦЕНКИ (строгая). По каждому критерию выбери уровень: "
        '"met" — выполнено грамотно и с результатом; "partial" — частично; '
        '"not_met" — не выполнено; "na" — в этом звонке неприменимо '
        "(например, возражений не было). Сомневаешься между уровнями — "
        "ставь нижний. Неумелая, невнятная или неудачная попытка — это не "
        '"met". Если менеджер пытался, но клиент по существу не ответил — '
        '"not_met". Не хвали за старание: только за результат.',
    ]
    for key, weight, met, partial, not_met in CRITERIA:
        lines.append(
            f"- {key} (вес {weight}): met — {met}; partial — {partial}; not_met — {not_met}."
        )
    return "\n".join(lines)


def rubric_json_hint() -> str:
    keys = ", ".join(f'"{k}"' for k, *_ in CRITERIA)
    return (
        '"rubric": [{"key": одно из [' + keys + '], "level": "met|partial|not_met|na", '
        '"evidence": "короткая цитата из расшифровки, на которой основан уровень", '
        '"comment": "что именно не так и как надо, 1 предложение"}] — ровно по одному на каждый критерий'
    )


def score(rubric: list[dict[str, Any]] | None) -> int | None:
    """Балл 0–10 по уровням и весам. Жёсткие потолки: без следующего
    шага — не выше 5; провал выявления потребности — не выше 6."""
    if not rubric:
        return None
    weights = {k: w for k, w, *_ in CRITERIA}
    levels = {r.get("key"): r.get("level") for r in rubric if isinstance(r, dict)}
    got = total = 0
    for key, w in weights.items():
        level = levels.get(key)
        if level not in LEVEL_POINTS:
            continue  # na или нет оценки — не участвует
        got += LEVEL_POINTS[level] * w
        total += 2 * w
    if total == 0:
        return None
    value = round(10 * got / total)
    if levels.get("next_step") == "not_met":
        value = min(value, 5)
    if levels.get("discovery") == "not_met":
        value = min(value, 6)
    return max(0, min(10, value))


def talk_share(segments: list[dict[str, Any]] | None) -> float | None:
    """Доля реплик клиента по объёму текста — для критерия «слушает»."""
    if not segments:
        return None
    rep = sum(len(s.get("text") or "") for s in segments if s.get("speaker") == "rep")
    client = sum(len(s.get("text") or "") for s in segments if s.get("speaker") == "client")
    if rep + client == 0:
        return None
    return client / (rep + client)
